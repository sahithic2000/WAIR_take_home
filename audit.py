"""Compare model accuracy before and after gold-label edits; write audit.md."""
from pathlib import Path

from eval.score import score_model
from eval.validate_answer import regenerate_test_questions
from run_eval import load_jsonl

ROOT = Path(__file__).resolve().parent


def corrected_gold_labels():
    
    """Generate corrected labels, score both versions, and write audit.md."""

    original_rows = load_jsonl("test_questions.jsonl")
    original = {row["id"]: row.copy() for row in original_rows}
    corrected_path = ROOT / "data" / "test_questions_correct.jsonl"
    regenerate_test_questions([row.copy() for row in original_rows], corrected_path)
    corrected = {row["id"]: row for row in load_jsonl("test_questions_correct.jsonl")}
    if set(original) != set(corrected):
        raise ValueError("Original and corrected question IDs do not match")

    outputs = {
        "A": {row["id"]: row["response"] for row in load_jsonl("model_a_outputs.jsonl")},
        "B": {row["id"]: row["response"] for row in load_jsonl("model_b_outputs.jsonl")},
    }
    before = {model: score_model(responses, original) for model, responses in outputs.items()}
    after = {model: score_model(responses, corrected) for model, responses in outputs.items()}
    edits = [qid for qid in original if original[qid]["gold_answer"] != corrected[qid]["gold_answer"]]

    lines = [
        "# Gold-label correction audit", "",
        "Generated by `python audit.py`. Unparseable responses are excluded by the existing scorer.", "",
        f"Gold answers changed: {len(edits)} of {len(original)}.", "",
        "| Model | Before | After | Change | Scored | Unparseable |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for model in ("A", "B"):
        old, new = before[model], after[model]
        lines.append(
            f"| {model} | {old['accuracy']:.1%} | {new['accuracy']:.1%} | "
            f"{(new['accuracy'] - old['accuracy']) * 100:+.1f} pp | "
            f"{new['n_scored']} | {new['n_unparseable']} |"
        )

    old_gap = before["B"]["accuracy"] - before["A"]["accuracy"]
    new_gap = after["B"]["accuracy"] - after["A"]["accuracy"]

    lines += [
        "",
        "The updated labels are taken from `data/test_questions_correct.jsonl`.",
        "",
    ]

    lines += [
        "",
        f"B−A accuracy gap: {old_gap * 100:.1f} pp before corrections and "
        f"{new_gap * 100:.1f} pp after corrections.",
        "",
        "## Changed labels", "",
        "| Question ID | Old gold | Updated gold |",
        "|---|---:|---:|",
    ]
    for qid in edits:
        lines.append(
            f"| {qid} | {original[qid]['gold_answer']} | {corrected[qid]['gold_answer']} |"
        )

    report = "\n".join(lines)
    output_path = ROOT / "results" / "audit.md"
    output_path.write_text(report, encoding="utf-8")

if __name__ == "__main__":
    corrected_gold_labels()
